pub fn verify_signed_image() -> Result<(), &'static str> {
    let keys = [PUBLIC_KEY];
    let policy = UpdatePolicy {
        trusted_keys: &keys,
        min_security_version: 1,
    };
    let signed = SignedManifest::from_bytes(&MANIFEST).map_err(|_| "parse")?;
    let manifest = policy
        .check(&signed)
        .map_err(|_| "valid manifest rejected")?;
    if manifest.build_id != 7 || manifest.version.as_str() != "1.0.0" {
        return Err("wrong manifest fields");
    }

    let mut v = ImageVerifier::new(manifest);
    v.update(&IMAGE).map_err(|_| "update")?;
    v.finish().map_err(|_| "image rejected")
}

pub fn reject_tampered_and_rollback() -> Result<(), &'static str> {
    let keys = [PUBLIC_KEY];

    let mut bytes = MANIFEST;
    bytes[20] ^= 1; // image_size
    let tampered = SignedManifest::from_bytes(&bytes).map_err(|_| "parse")?;
    if tampered.verify(&keys) != Err(ManifestError::BadSignature) {
        return Err("tampered manifest accepted");
    }

    let mut image = IMAGE;
    image[0] ^= 1;
    let signed = SignedManifest::from_bytes(&MANIFEST).map_err(|_| "parse")?;
    let manifest = signed.verify(&keys).map_err(|_| "verify")?;
    let mut v = ImageVerifier::new(manifest);
    v.update(&image).map_err(|_| "update")?;
    if v.finish() != Err(ManifestError::HashMismatch) {
        return Err("modified image accepted");
    }

    let policy = UpdatePolicy {
        trusted_keys: &keys,
        min_security_version: 2,
    };
    match policy.check(&signed) {
        Err(ManifestError::Rollback { .. }) => Ok(()),
        _ => Err("rollback accepted"),
    }
}
